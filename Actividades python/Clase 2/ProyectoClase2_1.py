#Le pido al usuario los dato.
print("Ingrese dos numeros.")
#Recibo los dos datos, los guardo en una variable
#y lo convierto a un entero para poder realizar las operaciones.
n1=int(input("Numero 1: "))
n2=int(input("Numero 2: "))
#Imprimo el resultado de cada ocasion.
print(f"La suma de los dos numeros es: {n1+n2}")
print(f"La resta de los dos numeros es: {n1-n2}")
print(f"La multiplicacion de los dos numeros es: {n1*n2}")
print(f"El resto de la division de los dos numeros es: {n1%n2}")